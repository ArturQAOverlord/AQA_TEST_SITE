"""Трек «Manual QA»: тесты с вопросами для ручного тестировщика.

Каждый тест (Quiz) — набор вопросов от простых к сложным. Правильные ответы
живут только здесь, на сервере: страница получает вопросы без ответов и
проверяет каждый ответ запросом к /api/qa/<тест>/check.

Типы вопросов:
  single — один правильный вариант (answer — индекс варианта);
  multi  — несколько правильных (answer — множество индексов);
  text   — ввод ответа (answer — допустимые ответы, сравниваются после нормализации).

Варианты на странице перемешиваются, поэтому порядок здесь значения не имеет.
Неверные варианты должны быть правдоподобными: типичные заблуждения и путаница
терминов, а не заведомая чепуха, которую отбрасываешь не читая.
"""

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Question:
    id: str
    kind: str
    text: str
    options: tuple[str, ...]
    answer: object
    explanation: str
    placeholder: str = ""


@dataclass(frozen=True)
class Topic:
    id: str
    title: str


@dataclass(frozen=True)
class Quiz:
    slug: str
    topic: str
    title: str
    level: str
    summary: str
    questions: tuple[Question, ...]
    # Практикумы: стенд /qa/lab/<sandbox>, на котором ищутся ответы
    sandbox: str | None = None


def single(text, options, answer, explanation):
    return ("single", text, tuple(options), answer, explanation, "")


def multi(text, options, answers, explanation):
    return ("multi", text, tuple(options), frozenset(answers), explanation, "")


def text(text_, accepted, explanation, placeholder="Твой ответ"):
    return ("text", text_, (), tuple(accepted), explanation, placeholder)


def quiz(slug, topic, title, level, summary, questions, sandbox=None):
    built = tuple(Question(f"{slug}-{i}", *q) for i, q in enumerate(questions, 1))
    return Quiz(slug, topic, title, level, summary, built, sandbox)


def normalize(value: str) -> str:
    """Нормализация текстового ответа: регистр, пробелы, кавычки, «₽», запятая в числах."""
    value = str(value).strip().lower().strip("\"'«»`")
    value = re.sub(r"\s+", "", value).replace("₽", "").replace("руб.", "").replace("руб", "")
    return value.replace(",", ".")


def check_answer(question: Question, answer) -> bool:
    if question.kind == "single":
        return isinstance(answer, int) and answer == question.answer
    if question.kind == "multi":
        return isinstance(answer, list) and set(answer) == set(question.answer)
    return isinstance(answer, str) and normalize(answer) in {normalize(a) for a in question.answer}


def answer_text(question: Question) -> str:
    if question.kind == "single":
        return question.options[question.answer]
    if question.kind == "multi":
        return "; ".join(question.options[i] for i in sorted(question.answer))
    return question.answer[0]


